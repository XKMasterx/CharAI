function getTranslation(key, lang = 'de') {
  if (!lang || lang === 'auto') {
    const browserLang = (navigator.language || 'de').slice(0, 2).toLowerCase();
    lang = I18N_TRANSLATIONS[browserLang] ? browserLang : 'en';
  }
  const dict = I18N_TRANSLATIONS[lang] || I18N_TRANSLATIONS['en'] || I18N_TRANSLATIONS['de'];
  return dict[key] || (I18N_TRANSLATIONS['en'] && I18N_TRANSLATIONS['en'][key]) || (I18N_TRANSLATIONS['de'] && I18N_TRANSLATIONS['de'][key]) || key;
}

function applyI18nToDOM(lang = 'de') {
  document.documentElement.lang = (lang === 'auto') ? (navigator.language || 'en').slice(0, 2) : lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const txt = getTranslation(key, lang);
    if (txt) el.textContent = txt;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const txt = getTranslation(key, lang);
    if (txt) el.placeholder = txt;
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const txt = getTranslation(key, lang);
    if (txt) el.title = txt;
  });
}
